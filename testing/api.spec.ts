/*
Common HTTP methods:

1. GET - Read Only - 200
Used to retrieve the data from a specified resource.

2. POST - Creating on the resource.
Used to submit data to be processed to a specific resource.

3. PUT - Updated or Create
Used to replace an existing resource BUT if the resource itself is not available then it will create a new record on the resource.

4. DELETE - Deleting the record
Used to request the removal of the resource.

5. PATCH - Particial modification
Used to apply partical modification to a resource.

*/ 
 
// Request Format
   // URL - Uniform Resource Locator
   // HTTP Method - GET, POST, PUT, DELETE
   // Headers - Key-value {key: value}
   // Body or Payload - JSON/XML, form data

// Response Format
   // Status Code - 200, 201, 400, 401, 500
   // Headers - {key: value}
   // Responnse body - JSON